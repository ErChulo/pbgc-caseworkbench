/**
 * Word (.docx) renderer for the plan summary.
 *
 * The document is generated from `PlanSummaryDocument` rows: the shell's
 * sections and labels with the case's recorded values, and an explicit
 * "Not recorded" for every cell the case does not hold. It does not fill the
 * original shell bytes (that file is not in the repository); it reproduces the
 * transcribed shell's structure and labels. The distinction is recorded in
 * `references/rules/bcv-add-ins.md`'s sibling work-product documentation and in
 * the README.
 *
 * Adapter code: writes OOXML bytes; no React, storage, or case access.
 */

import type {
  PlanSummaryDocument,
  PlanSummaryField,
} from "../../domain/work-products/r5/summaryDocument";
import { createStoredZip, type ZipEntry } from "./zip";

function escapeXml(text: string): string {
  return text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

type RunOptions = {
  bold?: boolean;
  italics?: boolean;
  color?: string;
  size?: number;
};

function run(text: string, options: RunOptions = {}): string {
  const properties = [
    options.bold ? "<w:b/>" : "",
    options.italics ? "<w:i/>" : "",
    options.color ? `<w:color w:val="${options.color}"/>` : "",
    options.size ? `<w:sz w:val="${options.size}"/><w:szCs w:val="${options.size}"/>` : "",
  ].join("");
  return `<w:r>${properties ? `<w:rPr>${properties}</w:rPr>` : ""}<w:t xml:space="preserve">${escapeXml(
    text,
  )}</w:t></w:r>`;
}

function paragraph(
  text: string,
  options: RunOptions & { style?: string; align?: string } = {},
): string {
  const properties = [
    options.style ? `<w:pStyle w:val="${options.style}"/>` : "",
    options.align ? `<w:jc w:val="${options.align}"/>` : "",
  ].join("");
  return `<w:p>${properties ? `<w:pPr>${properties}</w:pPr>` : ""}${run(text, options)}</w:p>`;
}

function tableRow(field: PlanSummaryField): string {
  const value = field.value ?? "Not recorded";
  const valueRun = field.value
    ? run(value)
    : run(value, { italics: true, color: "808080" });
  return `<w:tr>
<w:tc><w:tcPr><w:tcW w:w="3200" w:type="dxa"/></w:tcPr><w:p><w:pPr><w:pStyle w:val="TableText"/></w:pPr>${run(
    field.label,
    { bold: true },
  )}</w:p></w:tc>
<w:tc><w:tcPr><w:tcW w:w="6000" w:type="dxa"/></w:tcPr><w:p><w:pPr><w:pStyle w:val="TableText"/></w:pPr>${valueRun}</w:p></w:tc>
</w:tr>`;
}

function table(fields: readonly PlanSummaryField[]): string {
  const borders = ["top", "left", "bottom", "right", "insideH", "insideV"]
    .map(
      (side) =>
        `<w:${side} w:val="single" w:sz="4" w:space="0" w:color="BFBFBF"/>`,
    )
    .join("");
  return `<w:tbl>
<w:tblPr><w:tblW w:w="9200" w:type="dxa"/><w:tblBorders>${borders}</w:tblBorders></w:tblPr>
<w:tblGrid><w:gridCol w:w="3200"/><w:gridCol w:w="6000"/></w:tblGrid>
${fields.map(tableRow).join("\n")}
</w:tbl>`;
}

function sectionXml(sectionLabel: string, fields: readonly PlanSummaryField[]): string {
  return [paragraph(sectionLabel, { style: "Heading1" }), table(fields)].join("\n");
}

function documentXml(document: PlanSummaryDocument, planName: string | null): string {
  const header = document.sections.find((section) => section.label === "Header");
  const provisions = document.sections.filter(
    (section) => section.label !== "Header" && section.total > 0,
  );
  const incomplete = document.totals.filled < document.totals.total;
  const statusLine = incomplete
    ? `This summary is incomplete. ${document.totals.filled} of ${document.totals.total} items are recorded; every other cell is marked "Not recorded".`
    : "Every item in this summary has a recorded value.";

  const body: string[] = [];
  body.push(paragraph("Plan Summary", { style: "Title" }));
  if (planName) body.push(paragraph(planName, { style: "Subtitle" }));
  body.push(
    paragraph(`Case ${document.caseAlias}`, { style: "Small" }),
    paragraph(
      `Generated ${document.generatedAt.slice(0, 10)} · ${document.templateFileName}`,
      { style: "Small" },
    ),
  );
  body.push(paragraph(statusLine, { italics: true }));
  if (header) body.push(sectionXml(header.label, header.fields));
  for (const section of provisions) {
    body.push(sectionXml(section.label, section.fields));
  }
  body.push(
    paragraph(
      "Generated by the PBGC Case Workbench from recorded case data. This summary reports what the case holds; it is not a determination of benefits or a guarantee calculation.",
      { style: "Small" },
    ),
  );

  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
<w:body>
${body.join("\n")}
<w:sectPr><w:pgSz w:w="12240" w:h="15840"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440" w:header="720" w:footer="720" w:gutter="0"/></w:sectPr>
</w:body>
</w:document>`;
}

